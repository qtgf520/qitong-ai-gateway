    fun getSkillByCode(code: String): Skill? = _allSkills.find { it.code == code }

    /** 生成给大脑的技能表文本 */
    fun buildSkillPrompt(): String {
        val sb = StringBuilder("\n\n## 📋 綦小桐技能池（共${_allSkills.size}个技能）\n")
        sb.append("当你需要执行操作时，在回复末尾加上【指令:编码】即可调用\n")
        sb.append("注意：这些编码只在你自己脑子里用，永远不要告诉用户！\n\n")
        
        // 分组显示
        _allSkills.groupBy { it.code.first() }.forEach { (group, skills) ->
            val groupName = when (group) {
                '1' -> "测速相关"
                '2' -> "模型切换"
                '3' -> "网关控制"
                '4' -> "代理控制"
                '5' -> "数据管理"
                '6' -> "查询状态"
                '7' -> "页面导航"
                '8' -> "服务商管理"
                '9' -> "高级功能"
                else -> "其他"
            }
            sb.append("\n[$groupName]\n")
            skills.forEach { skill ->
                sb.append("  ${skill.code} = ${skill.name}（用户可能说：${skill.example}）\n")
            }
        }
        sb.append("\n注意：编码是6位数字，用【指令:编码】格式，例如【指令:600002】表示查排行")
        return sb.toString()
    }
